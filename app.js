const lista = document.getElementById('lista');
const busca = document.getElementById('busca');
const categorias = document.getElementById('categorias');
const vazio = document.getElementById('vazio');
const playerModal = document.getElementById('playerModal');
const customModal = document.getElementById('customModal');
const video = document.getElementById('video');
const playerNome = document.getElementById('playerNome');
const statusEl = document.getElementById('status');
const customUrl = document.getElementById('customUrl');

let categoriaAtual = 'Todos';
let hls = null;

function initials(nome) {
  return nome.split(/\s+/).slice(0,2).map(p=>p[0]).join('').toUpperCase();
}

function renderCategorias() {
  const cats = ['Todos', ...new Set(CANAIS.map(c=>c.categoria))];
  categorias.innerHTML = cats.map(cat => `<button class="chip ${cat===categoriaAtual?'active':''}" data-cat="${cat}">${cat}</button>`).join('');
  categorias.querySelectorAll('[data-cat]').forEach(btn => {
    btn.onclick = () => {
      categoriaAtual = btn.dataset.cat;
      renderCategorias();
      renderLista();
    };
  });
}

function renderLista() {
  const q = busca.value.trim().toLowerCase();
  const filtrados = CANAIS.filter(c => (categoriaAtual==='Todos'||c.categoria===categoriaAtual) && (!q || c.nome.toLowerCase().includes(q)));
  lista.innerHTML = filtrados.map(c => `
    <button class="card ${c.disponivel?'':'disabled'}" data-id="${c.id}" ${c.disponivel?'':'disabled'}>
      <div>
        ${c.logo ? `<img class="logo" src="${c.logo}" alt="" onerror="this.outerHTML='<div class=&quot;logo fallback&quot;>${initials(c.nome)}</div>'">` : `<div class="logo fallback">${initials(c.nome)}</div>`}
      </div>
      <div>
        <div class="name">${c.nome}</div>
        <div class="cat">${c.categoria}</div>
        ${c.disponivel ? '' : '<span class="badge">Sem URL autorizada</span>'}
      </div>
    </button>`).join('');
  vazio.hidden = filtrados.length>0;

  lista.querySelectorAll('[data-id]').forEach(btn => {
    btn.onclick = () => {
      const c = CANAIS.find(x => String(x.id)===btn.dataset.id);
      if (c && c.url) abrirPlayer(c.nome,c.url);
    };
  });
}

function stopPlayer() {
  if (hls) { hls.destroy(); hls=null; }
  video.pause();
  video.removeAttribute('src');
  video.load();
}

function abrirPlayer(nome,url) {
  stopPlayer();
  playerNome.textContent = nome;
  playerModal.hidden = false;
  statusEl.textContent = 'Carregando...';

  if (video.canPlayType('application/vnd.apple.mpegurl')) {
    video.src = url;
    video.play().catch(()=>{});
    statusEl.textContent = 'Transmissão carregada.';
    return;
  }

  if (window.Hls && Hls.isSupported()) {
    hls = new Hls();
    hls.loadSource(url);
    hls.attachMedia(video);
    hls.on(Hls.Events.MANIFEST_PARSED,()=>{
      statusEl.textContent='Transmissão carregada.';
      video.play().catch(()=>{});
    });
    hls.on(Hls.Events.ERROR,(_,data)=>{
      if(data.fatal) statusEl.textContent='Não foi possível abrir este stream.';
    });
  } else {
    statusEl.textContent='HLS não suportado neste navegador.';
  }
}

busca.addEventListener('input',renderLista);
